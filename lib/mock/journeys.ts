export function buildJourneys(rangeKey: TimeRangeKey): BusinessJourney[] {
  return BLUEPRINTS.map((b) => {
    const successRate = buildSeries(
      {
        id: `${b.id}:success-rate`,
        label: "Journey success rate",
        unit: "pct",
        base: b.baseSuccess,
        noise: 0.004,
        min: 40,
        max: 100,
        decimals: 2,
        baseline: b.slo?.successRatePct,
        events: b.successEvents,
        markers: b.changeIds.length
          ? [{ t: T.deploy, label: "Deployment", kind: "change", refId: b.changeIds[0] }]
          : undefined,
      },
      rangeKey,
    );

    const latency = buildSeries(
      {
        id: `${b.id}:latency`,
        label: "Journey p95 latency",
        unit: "ms",
        base: b.baseLatency,
        noise: 0.09,
        seasonality: 0.08,
        min: 40,
        baseline: b.slo?.p95LatencyMs,
        events: b.latencyEvents,
      },
      rangeKey,
    );

    const revenue = b.revenuePerMinute
      ? buildSeries(
          {
            id: `${b.id}:revenue`,
            label: "Revenue per minute",
            unit: "currency",
            base: b.revenuePerMinute,
            noise: 0.06,
            seasonality: 0.18,
            min: 0,
            events: b.successEvents?.map((e) => ({
              ...e,
              delta: undefined,
              multiplier: 1 - Math.abs(e.delta ?? 0) / 100,
            })),
          },
          rangeKey,
        )
      : undefined;

    const journey: BusinessJourney = {
      id: b.id,
      name: b.name,
      businessDescription: b.businessDescription,
      criticality: b.criticality,
      discovery: b.discovery,
      owner: b.owner,
      slo: b.slo,
      health: b.health,
      healthScore: b.healthScore,
      steps: b.steps.map(toStep),
      applicationIds: b.applicationIds,
      customersInWindow: b.customersInWindow,
      customersAffected: b.customersAffected,
      transactionsInWindow: b.transactionsInWindow,
      transactionsFailed: b.transactionsFailed,
      successRatePct: b.successRatePct,
      successRateTrend: makeTrend(b.successRateChangePct, "up-is-good", rangeKey),
      p95LatencyMs: b.p95LatencyMs,
      latencyTrend: makeTrend(b.latencyChangePct, "down-is-good", rangeKey),
      conversionRatePct: b.conversionRatePct,
      conversionImpactPct: b.conversionImpactPct,
      observedValue: observed(b.observedValue),
      valueAtRisk: usd(b.valueAtRisk),
      revenuePerTransaction: observed(b.revenuePerTransaction),
      currency: "USD",
      regionalHealth: b.regionalHealth,
      series: { successRate, latency, revenue },
      incidentIds: b.incidentIds,
      changeIds: b.changeIds,
      rootCauseId: b.rootCauseId,
      degradedSince: b.degradedSince,
    };
    return journey;
  });
}

export const JOURNEY_IDS = BLUEPRINTS.map((b) => b.id);

export const JOURNEY_NAMES: Record<string, string> = Object.fromEntries(
  BLUEPRINTS.map((b) => [b.id, b.name]),
);

export function journeyBlueprint(id: string) {
  return BLUEPRINTS.find((b) => b.id === id);
}
