export function buildServices(rangeKey: TimeRangeKey): Service[] {
  return BLUEPRINTS.map((b) => {
    const service: Service = {
      id: b.id,
      name: b.name,
      kind: b.kind,
      applicationId: b.applicationId,
      owner: b.owner,
      environment: "production",
      health: b.health,
      p95LatencyMs: b.p95LatencyMs,
      errorRatePct: b.errorRatePct,
      throughputRps: b.throughputRps,
      saturationPct: b.saturationPct,
      dependencyIds: b.dependencyIds,
      infrastructureIds: b.infrastructureIds,
      region: b.region,
      incidentIds: b.incidentIds,
      changeIds: b.changeIds,
      vendor: b.vendor,
      series: {
        latency: buildSeries(
          {
            id: `${b.id}:latency`,
            label: `${b.name} p95 latency`,
            unit: "ms",
            base: b.p95LatencyMs / (b.latencyEvents?.[0]?.multiplier ?? 1),
            noise: 0.08,
            seasonality: 0.07,
            min: 1,
            events: b.latencyEvents,
          },
          rangeKey,
        ),
        errorRate: buildSeries(
          {
            id: `${b.id}:error-rate`,
            label: `${b.name} error rate`,
            unit: "pct",
            base: Math.max(0.02, b.errorRatePct - (b.errorEvents?.[0]?.delta ?? 0)),
            noise: 0.18,
            min: 0,
            max: 100,
            decimals: 2,
            events: b.errorEvents,
          },
          rangeKey,
        ),
        saturation:
          b.saturationPct === undefined
            ? undefined
            : buildSeries(
                {
                  id: `${b.id}:saturation`,
                  label: `${b.name} saturation`,
                  unit: "pct",
                  base: Math.max(5, b.saturationPct - (b.saturationEvents?.[0]?.delta ?? 0)),
                  noise: 0.06,
                  seasonality: 0.1,
                  min: 0,
                  max: 100,
                  decimals: 1,
                  events: b.saturationEvents,
                },
                rangeKey,
              ),
      },
    };
    return service;
  });
}

