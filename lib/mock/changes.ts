export const CHANGES_BY_ID = new Map(CHANGES.map((c) => [c.id, c]));

export function changesByIds(ids: string[]): Change[] {
  return ids.map((id) => CHANGES_BY_ID.get(id)).filter((c): c is Change => Boolean(c));
}

/** Changes touching any of the given entities, most recent first. */
export function changesTouching(entityIds: string[]): Change[] {
  const set = new Set(entityIds);
  return CHANGES.filter((c) =>
    [...c.targetIds, ...c.applicationIds, ...c.serviceIds, ...c.infrastructureIds].some((id) => set.has(id)),
  ).sort((a, b) => new Date(b.at).getTime() - new Date(a.at).getTime());
}
