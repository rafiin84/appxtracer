export function buildApplications(rangeKey: TimeRangeKey): Application[] {
  return BLUEPRINTS.map((b) => {
    const latency = buildSeries(
      {
        id: `${b.id}:latency`,
        label: `${b.name} p95 latency`,
        unit: "ms",
        base: b.baseLatency,
        noise: 0.08,
        seasonality: 0.09,
        min: 30,
        events: b.latencyEvents,
        markers: b.changeIds.length
          ? [{ t: T.deploy, label: "Deployment", kind: "change", refId: b.changeIds[0] }]
          : undefined,
      },
      rangeKey,
    );
    const errorRate = buildSeries(
      {
        id: `${b.id}:error-rate`,
        label: `${b.name} error rate`,
        unit: "pct",
        base: b.baseErrorRate,
        noise: 0.16,
        min: 0,
        max: 100,
        decimals: 2,
        events: b.errorEvents,
      },
      rangeKey,
    );
    const throughput = buildSeries(
      {
        id: `${b.id}:throughput`,
        label: `${b.name} throughput`,
        unit: "rps",
        base: b.throughputRps,
        noise: 0.05,
        seasonality: 0.22,
        min: 0,
        events: b.throughputEvents,
      },
      rangeKey,
    );

    const app: Application = {
      id: b.id,
      name: b.name,
      kind: b.kind,
      description: b.description,
      environment: "production",
      criticality: b.criticality,
      owner: b.owner,
      health: b.health,
      healthScore: b.healthScore,
      journeyIds: b.journeyIds,
      serviceIds: b.serviceIds,
      dependencyIds: b.dependencyIds,
      customersAffected: b.customersAffected,
      customersServed: b.customersServed,
      p95LatencyMs: b.p95LatencyMs,
      latencyTrend: makeTrend(b.latencyChangePct, "down-is-good", rangeKey),
      errorRatePct: b.errorRatePct,
      errorRateTrend: makeTrend(b.errorRateChangePct, "down-is-good", rangeKey),
      throughputRps: b.throughputRps,
      availabilityPct: b.availabilityPct,
      apdex: b.apdex,
      valueAtRisk: usd(b.valueAtRisk),
      observedValue: observed(b.observedValue),
      regions: b.regions,
      series: { latency, errorRate, throughput },
      incidentIds: b.incidentIds,
      changeIds: b.changeIds,
      likelyRootCauseId: b.likelyRootCauseId,
      degradedSince: b.degradedSince,
      sourceIds: b.sourceIds,
    };
    return app;
  });
}

export const APPLICATION_NAMES: Record<string, string> = Object.fromEntries(
  BLUEPRINTS.map((b) => [b.id, b.name]),
);

export const APPLICATION_IDS = BLUEPRINTS.map((b) => b.id);

